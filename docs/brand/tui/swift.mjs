/**
 * The scene as Swift source, so the product draws the *same* crab the README does.
 *
 * The card cannot shell out to Node, and a hand-kept copy of the drawing is the thing this whole
 * exercise exists to kill: the old card was twelve shapes transcribed into `LoadingView.swift`, and
 * the day the drawing changed, the two were different animals. So `logo-tui.mjs --swift` writes
 * `Sources/krd/MascotArt.swift` from the same `scene()` the SVG comes from, and `MascotRaster`
 * (hand-written, next to it) is the only code that knows how to draw it.
 *
 * What crosses the language boundary is deliberately the *vocabulary* of vector.mjs, nothing more:
 * absolute `M`/`L`/`C`/`Z` paths, a colour or a user-space gradient, a nonzero/evenodd rule, an
 * alpha, a stroke width, a group transform, a clip. No filters, no masks, no text — the same
 * constraint SVG 1.1 and CoreGraphics share.
 */
import { pathData, chain, groupDef } from './vector.mjs';

const num = (v, dp = 1) => {
  const s = (Math.round(v * 10 ** dp) / 10 ** dp).toFixed(dp).replace(/\.?0+$/, '');
  return s === '-0' ? '0' : s;
};
const str = s => JSON.stringify(s);

/** A paint as one string: `#rrggbb`, `@L x1 y1 x2 y2 o:h:a…`, `@R cx cy r o:h:a…`. */
export function paint(p) {
  if (typeof p === 'string') return p;
  const stops = p.stops.map(([o, h, a = 1]) => `${num(o, 3)}:${h}:${num(a, 3)}`).join(' ');
  return p.type === 'linear'
    ? `@L ${num(p.x1)} ${num(p.y1)} ${num(p.x2)} ${num(p.y2)} ${stops}`
    : `@R ${num(p.cx)} ${num(p.cy)} ${num(p.r)} ${stops}`;
}

/**
 * The Swift file. `lod` decides which drawing is baked in — the card only ever draws `'lo'`, so
 * that is the default and the only thing the app carries.
 */
export function emitSwift(scene, { lod = 'lo', beats, view, source = 'docs/brand/tui/mascot.mjs' } = {}) {
  const layers = scene.layers.filter(l => !l.lod || l.lod === lod);
  const groups = Object.keys(scene.groups);
  const box = view || scene.view;

  /* the pose each beat asks for, resolved to numbers: a beat is `{ move: {group: [dx, dy]},
     turn: {group: deg}, eyes }`, and the card only has translations, but the shape is general */
  const poses = beats.map(p => {
    const move = Object.entries(p.move || {}).filter(([, v]) => v[0] || v[1])
      .map(([g, v]) => `${str(g)}: [${num(v[0])}, ${num(v[1])}]`).join(', ');
    const turn = Object.entries(p.turn || {}).filter(([, v]) => v)
      .map(([g, v]) => `${str(g)}: ${num(v)}`).join(', ');
    return `MascotPose(move: ${move ? `[${move}]` : '[:]'}, turn: ${turn ? `[${turn}]` : '[:]'}, shut: ${p.eyes === 'shut'})`;
  });

  const groupSrc = groups.map(g => {
    const d = groupDef(scene, g, lod);
    const pivot = d.pivot || [0, 0];
    const clip = d.clip ? `MascotClip(d: ${str(pathData(d.clip.d))}, evenOdd: ${d.clip.rule === 'evenodd'})` : 'nil';
    return `        ${str(g)}: MascotGroup(parent: ${d.parent ? str(d.parent) : 'nil'}, `
      + `pivot: [${num(pivot[0])}, ${num(pivot[1])}], clip: ${clip}),`;
  }).join('\n');

  const layerSrc = layers.map(l => {
    const parts = [
      `d: ${str(pathData(l.d))}`,
      `fill: ${l.fill ? str(paint(l.fill)) : 'nil'}`,
      `stroke: ${l.stroke ? str(paint(l.stroke)) : 'nil'}`,
      `width: ${num(l.w || 0)}`,
      `alpha: ${num(l.alpha ?? 1, 3)}`,
      `evenOdd: ${l.rule === 'evenodd'}`,
      `under: ${!!l.under}`,
      `group: ${l.group ? str(l.group) : 'nil'}`,
      `only: ${l.only ? str(l.only) : 'nil'}`,
      `clip: ${l.clip ? `MascotClip(d: ${str(pathData(l.clip.d))}, evenOdd: ${l.clip.rule === 'evenodd'})` : 'nil'}`,
    ];
    return `        MascotLayer(${parts.join(', ')}),`;
  }).join('\n');

  /* the palette: every opaque colour in the drawing, plus the paper the card paints on. The mosaic
     quantises to it, because a half-block cell is one colour and an AA edge is not one. */
  const flat = p => !p ? [] : typeof p === 'string' ? [p] : (p.stops || []).map(([, h]) => h);
  const palette = [...new Set(layers.flatMap(l => [...flat(l.fill), ...flat(l.stroke)]))].sort();

  return `// Generated by \`node docs/brand/tui/logo-tui.mjs --swift\` — do not edit.
//
// The drawing is ${source}, reached through docs/brand/tui/vector.mjs: one scene, drawn as the
// README's SVG, as the lab's terminal sprites and — here — as krd's loading card. Change the
// drawing and re-run the command; a hand edit is the drift this file exists to prevent.

/// One layer of the mascot: what vector.mjs calls a layer, with the strings it can carry.
struct MascotLayer {
    let d: String
    let fill: String?
    let stroke: String?
    let width: Double
    let alpha: Double
    let evenOdd: Bool
    /// Paint the stroke before the fill (SVG's \`paint-order: stroke\`): an outline that only shows
    /// outside the shape, so a thin limb keeps all of its colour.
    let under: Bool
    let group: String?
    /// \`"open"\`/\`"shut"\`: drawn only when the pose's eyes are.
    let only: String?
    let clip: MascotClip?
}

struct MascotClip {
    let d: String
    let evenOdd: Bool
}

struct MascotGroup {
    let parent: String?
    let pivot: [Double]
    let clip: MascotClip?
}

/// How one beat of the loading animation moves the drawing.
struct MascotPose {
    let move: [String: [Double]]
    let turn: [String: Double]
    let shut: Bool
}

enum MascotArt {
    /// The box the sprite lives in, in user units: every beat's ink plus a margin.
    static let view: [Double] = [${box.map(v => num(v)).join(', ')}]

    static let groups: [String: MascotGroup] = [
${groupSrc}
    ]

    static let layers: [MascotLayer] = [
${layerSrc}
    ]

    /// One beat per 110 ms in the fallback, per 220 ms in the picture: emergence, blink, retreat.
    static let poses: [MascotPose] = [
${poses.map(p => `        ${p},`).join('\n')}
    ]

    /// Every opaque colour in the drawing; the mosaic quantises its AA edges to these.
    static let palette: [String] = [${[...new Set([...palette, '#080a10'])].sort().map(str).join(', ')}]
}
`;
}
